INV_SBOX = [0] * 256
for _i, _v in enumerate(SBOX):
    INV_SBOX[_v] = _i

RCON = [0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1b,0x36,0x6c,0xd8,0xab,0x4d]


def _xtime(a):
    a <<= 1
    if a & 0x100:
        a = (a ^ 0x1b) & 0xff
    return a


def _mul(a, b):
    """Multiply in GF(2^8)."""
    r = 0
    for _ in range(8):
        if b & 1:
            r ^= a
        b >>= 1
        a = _xtime(a)
    return r


def expand_key(key):
    """AES key schedule. Returns Nr+1 round keys of 16 bytes each."""
    nk = len(key) // 4
    nr = nk + 6
    w = [list(key[4 * i:4 * i + 4]) for i in range(nk)]
    for i in range(nk, 4 * (nr + 1)):
        t = list(w[i - 1])
        if i % nk == 0:
            t = t[1:] + t[:1]
            t = [SBOX[b] for b in t]
            t[0] ^= RCON[i // nk - 1]
        elif nk > 6 and i % nk == 4:
            t = [SBOX[b] for b in t]
        w.append([w[i - nk][j] ^ t[j] for j in range(4)])
    return [bytes(b for word in w[4 * r:4 * r + 4] for b in word) for r in range(nr + 1)], nr


def _decrypt_block(block, round_keys, nr):
    s = [b ^ k for b, k in zip(block, round_keys[nr])]
    for rnd in range(nr - 1, -1, -1):
        # InvShiftRows
        t = list(s)
        for r in range(1, 4):
            for c in range(4):
                t[((c + r) % 4) * 4 + r] = s[c * 4 + r]
        # InvSubBytes
        t = [INV_SBOX[b] for b in t]
        # AddRoundKey
        t = [b ^ k for b, k in zip(t, round_keys[rnd])]
        if rnd:
            # InvMixColumns
            out = []
            for c in range(4):
                col = t[4 * c:4 * c + 4]
                out += [
                    _mul(col[0], 14) ^ _mul(col[1], 11) ^ _mul(col[2], 13) ^ _mul(col[3], 9),
                    _mul(col[0], 9) ^ _mul(col[1], 14) ^ _mul(col[2], 11) ^ _mul(col[3], 13),
                    _mul(col[0], 13) ^ _mul(col[1], 9) ^ _mul(col[2], 14) ^ _mul(col[3], 11),
                    _mul(col[0], 11) ^ _mul(col[1], 13) ^ _mul(col[2], 9) ^ _mul(col[3], 14),
                ]
            t = out
        s = t
    return bytes(s)


def aes_cbc_decrypt(key, iv, data, unpad=True):
    """AES-CBC decrypt. Strips PKCS#7 padding unless unpad=False."""
    if len(data) % 16:
        raise ValueError(f"ciphertext length {len(data)} is not a multiple of 16")
    round_keys, nr = expand_key(key)
    out = bytearray()
    prev = iv
    for i in range(0, len(data), 16):
        ct = data[i:i + 16]
        out += bytes(a ^ b for a, b in zip(_decrypt_block(ct, round_keys, nr), prev))
        prev = ct
    if unpad:
        n = out[-1]
        if not 1 <= n <= 16 or bytes(out[-n:]) != bytes([n]) * n:
            raise ValueError("bad PKCS#7 padding - wrong key, IV, or cipher mode")
        del out[-n:]
    return bytes(out)
